internal fun localizeNetworkLabel(rawLabel: String, text: UiStrings): String = when (rawLabel) {
    "Offline" -> text.networkOffline
    "Connected" -> text.networkConnected
    "Local network" -> text.networkLocal
    "Checking network…" -> text.waiting
    else -> rawLabel
}

internal fun formatMediaBytes(bytes: Long): String = when {
    bytes >= 1024L * 1024L -> String.format(Locale.US, "%.1f MB", bytes / (1024.0 * 1024.0))
    bytes >= 1024L -> String.format(Locale.US, "%.1f KB", bytes / 1024.0)
    else -> "$bytes B"
}

internal fun stageTitle(stage: ProtocolStage, text: UiStrings): String = when (stage) {
    ProtocolStage.DISCOVERY -> text.discovery
    ProtocolStage.NEGOTIATION -> text.capabilities
    ProtocolStage.FAIRPLAY -> text.fairPlay
    ProtocolStage.TRANSPORT -> text.transport
    ProtocolStage.STREAMING -> text.media
}

internal fun toUiStage(stage: com.atrishub.atriscast.receiver.ProtocolStage): ProtocolStage = when (stage) {
    com.atrishub.atriscast.receiver.ProtocolStage.DISCOVERY -> ProtocolStage.DISCOVERY
    com.atrishub.atriscast.receiver.ProtocolStage.NEGOTIATION -> ProtocolStage.NEGOTIATION
    com.atrishub.atriscast.receiver.ProtocolStage.FAIRPLAY -> ProtocolStage.FAIRPLAY
    com.atrishub.atriscast.receiver.ProtocolStage.TRANSPORT -> ProtocolStage.TRANSPORT
    com.atrishub.atriscast.receiver.ProtocolStage.STREAMING -> ProtocolStage.STREAMING
}

